"""URDF writer.  Inertials from CAD, visual meshes per link, primitive
collisions, joint limits from the actuator spec, ros2_control-style
transmissions for the 26 actuated joints."""
from __future__ import annotations

import math
from pathlib import Path
from xml.sax.saxutils import escape

from spider import config as C
from spider.export.collision import collision_shapes
from spider.export.massprops import link_inertials
from spider.tf import rpy_of


def _f(v):
    return " ".join(f"{x:.6g}" for x in v)


def _origin(T_mm):
    return f'<origin xyz="{_f(T_mm[:3, 3] / 1000)}" rpy="{_f(rpy_of(T_mm))}"/>'


def _geom(kind, p):
    if kind == "box":
        return f'<box size="{_f([2 * x for x in p])}"/>'
    if kind == "sphere":
        return f'<sphere radius="{p[0]:.6g}"/>'
    if kind == "cylinder":
        return f'<cylinder radius="{p[0]:.6g}" length="{2 * p[1]:.6g}"/>'
    if kind == "capsule":   # URDF has no capsule: cylinder spanning the tips
        return f'<cylinder radius="{p[0]:.6g}" length="{2 * (p[1] + p[0]):.6g}"/>'
    raise ValueError(kind)


def write_urdf(robot, mesh_names: dict, path: Path, mesh_prefix="meshes/"):
    inert = link_inertials(robot)
    L = ['<?xml version="1.0"?>',
         '<!-- Generated by build.py from the part programs in spider/parts. Do not edit. -->',
         '<robot name="autonomous_spider">']
    for link in robot.links:
        I = inert[link]
        i = I.inertia
        L.append(f'  <link name="{link}">')
        L.append(f'    <!-- {I.n_parts} parts -->')
        L.append('    <inertial>')
        L.append(f'      <origin xyz="{_f(I.com)}" rpy="0 0 0"/>')
        L.append(f'      <mass value="{I.mass:.6g}"/>')
        L.append(f'      <inertia ixx="{i[0,0]:.6g}" ixy="{i[0,1]:.6g}" ixz="{i[0,2]:.6g}" '
                 f'iyy="{i[1,1]:.6g}" iyz="{i[1,2]:.6g}" izz="{i[2,2]:.6g}"/>')
        L.append('    </inertial>')
        L.append('    <visual>')
        L.append('      <origin xyz="0 0 0" rpy="0 0 0"/>')
        L.append(f'      <geometry><mesh filename="{mesh_prefix}{mesh_names[link]}"/></geometry>')
        L.append('    </visual>')
        for kind, p, pos, rpy in collision_shapes(link):
            L.append('    <collision>')
            L.append(f'      <origin xyz="{_f(pos)}" rpy="{_f(rpy)}"/>')
            L.append(f'      <geometry>{_geom(kind, p)}</geometry>')
            L.append('    </collision>')
        L.append('  </link>')
    for j in robot.joints:
        L.append(f'  <joint name="{j.name}" type="{j.type}">')
        L.append(f'    <parent link="{j.parent}"/>')
        L.append(f'    <child link="{j.child}"/>')
        L.append(f'    {_origin(j.origin)}')
        if j.type == "revolute":
            L.append(f'    <axis xyz="{_f(j.axis)}"/>')
            L.append(f'    <limit lower="{j.lower:.6g}" upper="{j.upper:.6g}" '
                     f'effort="{j.effort:.6g}" velocity="{j.velocity:.6g}"/>')
            L.append('    <dynamics damping="0.3" friction="0.4"/>')
        L.append('  </joint>')
    for j in robot.joints:
        if j.type != "revolute":
            continue
        knee = j.name.endswith("knee_joint")
        L.append(f'  <transmission name="{j.name.replace("_joint", "_trans")}">')
        L.append('    <type>transmission_interface/SimpleTransmission</type>')
        if knee:
            L.append('    <!-- 1:1 HTD-5M belt from a hip-mounted motor: motor angle = femur + knee. '
                     'The MJCF models this exactly with a fixed tendon. -->')
        L.append(f'    <joint name="{j.name}"><hardwareInterface>hardware_interface/EffortJointInterface'
                 f'</hardwareInterface></joint>')
        motor = escape(j.driver or "")
        gear = C.QDD_GEAR if j.name[0] in "LR" else 1.0
        L.append(f'    <actuator name="{j.name.replace("_joint", "_motor")}"><mechanicalReduction>{gear:g}'
                 f'</mechanicalReduction><!-- driver: {motor} --></actuator>')
        L.append('  </transmission>')
    L.append('</robot>')
    path.write_text("\n".join(L) + "\n")
    return inert
