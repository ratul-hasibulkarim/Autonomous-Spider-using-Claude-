"""MJCF (MuJoCo) writer: the physics model.

* body tree, joint axes/limits and inertials identical to the URDF
* visual meshes (group 1, no contact) + primitive collision geoms (group 3)
* actuators: 26 torque motors with the QDD-96 / GM-62 torque limits;
  each knee motor acts on a fixed tendon (femur + knee) - the 1:1 belt
* reflected rotor inertia (armature), joint damping and friction loss
* sensors: IMU (quat, gyro, accel), 8 foot touch sensors, joint state
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np

from spider import config as C
from spider.export.collision import collision_shapes
from spider.export.massprops import link_inertials, principal
from spider.tf import quat_of, rotx, roty, rotz

LEG_RGBA = "0.55 0.57 0.6 1"


def _f(v):
    return " ".join(f"{x:.6g}" for x in v)


def _quat_rpy(rpy):
    r, p, y = rpy
    return quat_of(rotz(math.degrees(y)) @ roty(math.degrees(p)) @ rotx(math.degrees(r)))


def _geom(kind, p, pos, rpy, name, extra=""):
    q = _quat_rpy(rpy)
    if kind == "box":
        g = f'type="box" size="{_f(p)}"'
    elif kind == "sphere":
        g = f'type="sphere" size="{p[0]:.6g}"'
    elif kind in ("cylinder", "capsule"):
        g = f'type="{kind}" size="{p[0]:.6g} {p[1]:.6g}"'
    else:
        raise ValueError(kind)
    return f'<geom name="{name}" class="collision" {g} pos="{_f(pos)}" quat="{_f(q)}"{extra}/>'


def write_mjcf(robot, mesh_names: dict, path: Path, mesh_dir="meshes"):
    inert = link_inertials(robot)
    children = {}
    for j in robot.joints:
        children.setdefault(j.parent, []).append(j)
    meshes = sorted(set(mesh_names.values()))
    L = ['<!-- Generated by build.py from the part programs in spider/parts. Do not edit. -->',
         '<mujoco model="autonomous_spider">',
         f'  <compiler angle="radian" meshdir="{mesh_dir}" autolimits="true"/>',
         '  <option timestep="0.002" integrator="implicitfast" cone="elliptic" impratio="10"/>',
         '  <default>',
         '    <joint damping="0.3" frictionloss="0.4"/>',
         '    <default class="visual"><geom group="1" contype="0" conaffinity="0" density="0"/></default>',
         '    <default class="collision"><geom group="3" contype="2" conaffinity="3" density="0" '
         'friction="0.8 0.02 0.002" rgba="0.8 0.3 0.2 0.4"/></default>',
         '    <default class="foot"><geom group="3" contype="2" conaffinity="3" density="0" '
         'friction="1.1 0.02 0.002" solref="0.008 1" solimp="0.92 0.98 0.002" condim="4" priority="1"/></default>',
         '  </default>',
         '  <asset>']
    for m in meshes:
        L.append(f'    <mesh name="{m[:-4]}" file="{m}"/>')
    L.append('  </asset>')
    L.append('  <worldbody>')

    def body(link, indent, joint=None):
        pad = " " * indent
        I = inert[link]
        if joint is None:
            L.append(f'{pad}<body name="{link}" pos="0 0 0.62">')
            L.append(f'{pad}  <freejoint name="root"/>')
        else:
            q = quat_of(joint.origin)
            L.append(f'{pad}<body name="{link}" pos="{_f(joint.origin[:3, 3] / 1000)}" quat="{_f(q)}">')
            if joint.type == "revolute":
                arm = C.QDD_ROTOR_INERTIA * C.QDD_GEAR ** 2 if link[:2] in {
                    f"{s}{i}" for s in "LR" for i in "1234"} else 0.002
                L.append(f'{pad}  <joint name="{joint.name}" axis="{_f(joint.axis)}" '
                         f'range="{joint.lower:.6g} {joint.upper:.6g}" armature="{arm:.4g}"/>')
        w, V = principal(I.inertia)
        L.append(f'{pad}  <inertial pos="{_f(I.com)}" quat="{_f(quat_of(np.block([[V, np.zeros((3, 1))], [np.zeros((1, 3)), np.ones((1, 1))]])))}" '
                 f'mass="{I.mass:.6g}" diaginertia="{_f(np.maximum(w, 1e-7))}"/>')
        rgba = LEG_RGBA if link[:2] in {f"{s}{i}" for s in "LR" for i in "1234"} else "0.35 0.36 0.4 1"
        L.append(f'{pad}  <geom class="visual" type="mesh" mesh="{mesh_names[link][:-4]}" rgba="{rgba}"/>')
        for k, (kind, p, pos, rpy) in enumerate(collision_shapes(link)):
            if link.endswith("_tibia") and kind == "sphere":
                L.append(f'{pad}  <geom name="{link[:2]}_foot" class="foot" type="sphere" size="{p[0]:.6g}" '
                         f'pos="{_f(pos)}"/>')
                L.append(f'{pad}  <site name="{link[:2]}_foot_site" type="sphere" size="{p[0] + 0.004:.6g}" '
                         f'pos="{_f(pos)}" rgba="0 1 0 0"/>')
            else:
                L.append(pad + "  " + _geom(kind, p, pos, rpy, f"{link}_col{k}"))
        if link == "imu_link":
            L.append(f'{pad}  <site name="imu" size="0.01"/>')
        if link == "lidar_link":
            L.append(f'{pad}  <site name="lidar" size="0.01"/>')
        if link == "front_camera_link":
            L.append(f'{pad}  <camera name="front_camera" mode="fixed" quat="0.5 0.5 -0.5 -0.5" fovy="70"/>')
        for j in children.get(link, []):
            body(j.child, indent + 2, j)
        L.append(f'{pad}</body>')

    body("base_link", 4)
    L.append('  </worldbody>')

    # self-collision: ignore pairs inside one leg that are not parent/child
    L.append('  <contact>')
    for leg in C.LEG_NAMES:
        L.append(f'    <exclude body1="{leg}_coxa" body2="{leg}_tibia"/>')
    L.append('    <exclude body1="base_link" body2="sensor_tilt"/>')
    L.append('    <exclude body1="base_link" body2="lidar_link"/>')
    L.append('  </contact>')

    L.append('  <tendon>')
    for leg in C.LEG_NAMES:
        L.append(f'    <fixed name="{leg}_knee_belt"><joint joint="{leg}_femur_joint" coef="1"/>'
                 f'<joint joint="{leg}_knee_joint" coef="1"/></fixed>')
    L.append('  </tendon>')

    t = C.QDD_TAU_PEAK
    L.append('  <actuator>')
    for leg in C.LEG_NAMES:
        L.append(f'    <motor name="{leg}_coxa_motor" joint="{leg}_coxa_joint" ctrlrange="{-t} {t}"/>')
        L.append(f'    <motor name="{leg}_femur_motor" joint="{leg}_femur_joint" ctrlrange="{-t} {t}"/>')
        L.append(f'    <motor name="{leg}_knee_motor" tendon="{leg}_knee_belt" ctrlrange="{-t} {t}"/>')
    g = C.GIMBAL_TAU_PEAK
    L.append(f'    <motor name="sensor_pan_motor" joint="sensor_pan_joint" ctrlrange="{-g} {g}"/>')
    L.append(f'    <motor name="sensor_tilt_motor" joint="sensor_tilt_joint" ctrlrange="{-g} {g}"/>')
    L.append('  </actuator>')

    L.append('  <sensor>')
    L.append('    <framequat name="imu_quat" objtype="site" objname="imu"/>')
    L.append('    <gyro name="imu_gyro" site="imu"/>')
    L.append('    <accelerometer name="imu_accel" site="imu"/>')
    for leg in C.LEG_NAMES:
        L.append(f'    <touch name="{leg}_foot_touch" site="{leg}_foot_site"/>')
    L.append('  </sensor>')
    L.append('</mujoco>')
    path.write_text("\n".join(L) + "\n")
    return inert
